// 根据时区自动检测语言：亚洲时区默认中文，其他默认英文
function detectLang() {
  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone
    if (tz && tz.startsWith('Asia/')) return 'zh'
    return 'en'
  } catch {
    return 'en'
  }
}

// 获取初始语言
function getInitialLang() {
  const stored = localStorage.getItem('lt_lang')
  if (stored === 'zh' || stored === 'en') return stored
  return detectLang()
}

// 翻译函数
function t(key, lang) {
  return (translations[lang] && translations[lang][key]) || translations['en'][key] || key
}

// ============ React Context ============
const LangContext = createContext({ lang: 'en', t: (k) => k, toggleLang: () => {} })

function useLang() {
  return useContext(LangContext)
}


// 模板字符串辅助函数：替换 {key} 占位符
function fmt(key, lang, params) {
  let text = (translations[lang] && translations[lang][key]) || translations['en'][key] || key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp('\\{' + k + '\\}', 'g'), v)
    }
  }
  return text
}

export { translations, detectLang, getInitialLang, t, fmt, LangContext, useLang }